	template <typename Data_t, typename Index_t>
	class ValidDataWrapper
	{
	public: 
		ValidDataWrapper(Data_t* data, Index_t* order, Index_t sample_size) : _data(data), _order(order) 
		{
			Index_t i;		
			_valid_data_count = 0;
			for ( i = 0; i < sample_size; i++ )
			{
				if (isValid(i))
				{  	
					if ( _valid_data_count < 3 ) 
					{
						Mins[_valid_data_count] = _data[_order[i]];
					}
					
					++_valid_data_count;										
				}
			}

			if ( _valid_data_count < 3 )
			{
				return;
			}

			TCSize_t accepted = 0;
			i = sample_size - 1;
			while (accepted < 3)
			{
				if (isValid(i))
				{
					Maxs[accepted] = _data[_order[i]];
					++ accepted;
				}
				--i;
			}								
		}
	
		Data_t& operator[](const Index_t& i) const
		{			
			Index_t Tmp = 0;
			Index_t k = 0;
		
			while ( Tmp != i + 1 )
			{
				Tmp += isValid(k);
				k++;
			}
			return _data[_order[k-1]];
		}
		
		Data_t& at(const Index_t& i) const
		{		
			Index_t _Tmp = 0;
			Index_t k = 0;
		
			while ( _Tmp != i + 1 )
			{
				_Tmp += isValid(k);
				k++;
			}
			return _data[_order[k-1]];
		 }

		Index_t getValidDataCount() const
		{
			return _valid_data_count;
		}

	bool isValid(const Index_t& k) const
		{
			if ( k == 0 )
			{
				return true;
			}
			if ( TCError::IsMissingImpl<Data_t>::run(&_data[_order[k]]) )
			{
				return false;
			}
			return  !_isequal<Data_t>(_data[_order[k]], _data[_order[k-1]]) ;
		}

		Data_t* _data;				
		Index_t* _order;
		Data_t Mins[3];
		Data_t Maxs[3];
	private:
		
		Index_t _valid_data_count ;

	};

	template <typename Data_t, typename Index_t>
	struct CheckingComparator
	{
		CheckingComparator(Data_t* data) : _data(data) {}
		
		bool operator()(const Index_t& _Left, const Index_t& _Right) throw (int) 
		{	
			Data_t a = _data[_Left];
			Data_t b = _data[_Right];
			bool isMissingA = TCError::IsMissing<Data_t>(&a);
			bool isMissingB = TCError::IsMissing<Data_t>(&b);			
						
			if (isMissingA)
			{
				return false;
			}
			else if (isMissingB)
			{
				return true;
			}
	
			if ( is_nan_or_inf_internal(a) || is_nan_or_inf_internal(b) )
			{
				throw (1);
			}

			return ( a < b );		
		}	

		Data_t* _data;					
	};

	
	
	
	
	template<typename T>
	inline bool is_nan_or_inf_internal(T a)
	{
		return ( isnan(a) || isnan(a - a) );
	};
	
	template <typename T>
	bool _isequal(T x, T y)
	{
		return ( fabs(x - y) < std::numeric_limits<T>::epsilon() );
	};
	
	
	
	
	
	
	
