	double p_value_approximation(TCSize_t n, TCSize_t j, TCSize_t iMinus1,  double r)
	{
		int approximation_region; 

		if (r<0.33) 
		{
			approximation_region = 0;
		}
		else if (r<0.75) 
		{
			approximation_region = 1;
		}
		else 
		{
			approximation_region = 2;
		}

		TCSize_t sample_size_ind = (n - 3)*3 + approximation_region;
		TCSize_t method_index = 3*(j - 1) + (iMinus1) % 3;

		double G; 

		G = dqt_cff_cff[method_index][sample_size_ind][8];	
		for (int i = 7; i >= 0; i --)
		{		
			G = G*r + dqt_cff_cff[method_index][sample_size_ind][i];
		}

		return 1.0 - G;			
	};

